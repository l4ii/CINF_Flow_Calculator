/**
 * 单一版本源：根目录 package.json 的 "version"
 * - 写入 frontend/src/generated/appVersion.ts（供前端导入）
 * - 更新 LICENSE.txt 中「版本号：」与英文「Version:」行（供 NSIS 许可证页经 convert-license-to-gbk 使用）
 */
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const pkgPath = path.join(root, 'package.json')

const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))
const version = String(pkg.version || '').trim()
if (!/^\d+\.\d+\.\d+/.test(version)) {
  console.error('[sync-app-version] package.json version 无效:', version)
  process.exit(1)
}

const genDir = path.join(root, 'frontend', 'src', 'generated')
fs.mkdirSync(genDir, { recursive: true })
const genFile = path.join(genDir, 'appVersion.ts')
fs.writeFileSync(
  genFile,
  `/* Auto-generated by scripts/sync-app-version.js — do not edit */\n` +
    `export const APP_VERSION = ${JSON.stringify(version)}\n`,
  'utf8'
)

const licensePath = path.join(root, 'LICENSE.txt')
if (fs.existsSync(licensePath)) {
  let lic = fs.readFileSync(licensePath, 'utf8')
  lic = lic.replace(/^版本号：.*$/m, `版本号：${version}`)
  lic = lic.replace(/^Version:\s*.+$/m, `Version: ${version}`)
  fs.writeFileSync(licensePath, lic, 'utf8')
}

console.log('[sync-app-version] 已同步版本', version, '→', path.relative(root, genFile))
